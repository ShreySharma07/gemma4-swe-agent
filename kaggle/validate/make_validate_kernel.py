"""
Build a Kaggle CPU kernel that compiles submissions with the OFFICIAL compiler (adk_submission + swegemma from the
competition wheelhouse) and prints each agent tree. Usage: python3 kaggle/validate/make_validate_kernel.py v7_noedit v2_sed
then: .venv/bin/kaggle kernels push -p kaggle/validate
"""
import base64, io, json, pathlib, sys, tarfile
ROOT = pathlib.Path(__file__).resolve().parents[2]
subs = sys.argv[1:] or ["v7_noedit"]
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tf:
    for s in subs:
        tf.add(ROOT / "submissions" / s, arcname=s)
blob = base64.b64encode(buf.getvalue()).decode()
code = f'''# generated by kaggle/validate/make_validate_kernel.py
import base64, glob, io, json, pathlib, subprocess, sys, tarfile
W = pathlib.Path("/kaggle/working"); S = W / "subs"; S.mkdir(exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode({blob!r})), mode="r:gz").extractall(S)
wh = pathlib.Path(sorted(glob.glob("/kaggle/input/**/swegemma-*.whl", recursive=True))[0]).parent
from packaging.tags import sys_tags
from packaging.utils import parse_wheel_filename
ok = set(sys_tags()); whls, pins = [], []
skip = ("torch", "vllm", "nvidia", "triton", "cutlass", "xformers", "flashinfer", "flash_attn", "cupy")
for w in wh.glob("*.whl"):
    if w.name.lower().startswith(skip): continue
    n, v, _, t = parse_wheel_filename(w.name)
    (whls.append(str(w)) if t & ok else pins.append(f"{{n}}=={{v}}"))
fails = []
for w in whls:  # one at a time: a single bad wheel must not abort the rest
    if subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", "--force-reinstall", w]).returncode:
        fails.append(pathlib.Path(w).name)
for p_ in pins:
    if subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", p_]).returncode:
        subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", p_.split("==")[0]])
import importlib, importlib.metadata as md
importlib.invalidate_caches()
print("wheel install failures:", fails)
print("swegemma", md.version("swegemma"), "adk-submission", md.version("adk-submission"), "google-adk", md.version("google-adk"))
from adk_submission import compile_submission
from adk_submission.discovery import discover_declared_models
from swegemma.config import build_submission_limits
from swegemma.cli import _build_cli_model_registry
from swegemma.harness.agent_runner import _extract_declared_tools
names = ["run_command","read_file","edit_file","write_file","get_status","submit_patch","get_code_neighbors","search_similar_code","get_code_subgraph"]
def mk(n):
    def f(**kw): return "{{}}"
    f.__name__ = n; f.__doc__ = n
    return f
tools = {{n: mk(n) for n in names}}
report = {{}}
for sub in sorted(S.iterdir()):
    try:
        models = _build_cli_model_registry(submission_dir=sub)
        declared = sorted(discover_declared_models(sub))
        limits, gen = build_submission_limits()
        agent = compile_submission(submission_dir=sub, tool_registry=tools, model_registry=models, limits=limits,
                                   generation_constraints=gen)
        tree = []
        def walk(a, d=0):
            tree.append("  " * d + f"{{type(a).__name__}} {{a.name}} tools={{[getattr(t,'name',getattr(t,'__name__',str(t))) for t in getattr(a,'tools',[]) or []]}}")
            for x in getattr(a, "sub_agents", []) or []: walk(x, d + 1)
        walk(agent)
        report[sub.name] = {{"ok": True, "model": declared, "tree": tree,
                             "declared_tools": sorted(_extract_declared_tools(agent) or [])}}
    except Exception as e:
        report[sub.name] = {{"ok": False, "error": f"{{type(e).__name__}}: {{e}}"[:1500]}}
(W / "validate.json").write_text(json.dumps(report, indent=1))
print(json.dumps(report, indent=1))
'''
(pathlib.Path(__file__).parent / "validate_kernel.py").write_text(code)
(pathlib.Path(__file__).parent / "kernel-metadata.json").write_text(json.dumps({
    "id": "shreysharma07/gemma4-validate-submission", "title": "gemma4-validate-submission", "code_file": "validate_kernel.py",
    "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_internet": True,
    "competition_sources": [], "dataset_sources": ["metric/gemma-4-developer-agent-wheelhouse"], "model_sources": [],
    "kernel_sources": []}, indent=2) + "\n")
print("wrote kernel for", subs)

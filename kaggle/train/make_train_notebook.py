"""
Build the LoRA training notebook from kaggle/train/trainkit (+ the env modules of kaggle/eval_l4/evalkit). Cells:
  1. settings          TrainSettings -> /kaggle/working/train_cfg.json (edit here to change the run)
  2. embedded inputs   the tokenized windows (.npz from posttrain/tokenize_windows.py) when small enough; the real
                       Gemma-4 config for the smoke model
  3. env modules       evalkit/{__init__,config,util,envsetup}.py (%%writefile)
  4. trainkit modules  one %%writefile cell per module
  5. scorer env        ScorerEnv().prepare_training(): Py3.12 venv + peft/bitsandbytes (stdlib only)
  6. train             python -m trainkit.main inside the venv (torchrun over 4 GPUs), streamed
  7. results           train_report.json
Targets:
  --smoke   free CPU kernel gemma4-train-smoke: tiny random Gemma-4, gloo, 2 ranks, same code path
  default   L4 kernel gemma4-train-lora (competition attached so it gets 4x L4); bf16 QAT weights -> NF4
Usage: python3 kaggle/train/make_train_notebook.py DATA.npz [--smoke] [--dataset owner/slug] [--max-windows N]
       [--budget-h 10.5] [--lr 1e-4] [--name conv_lora]
Then:  .venv/bin/kaggle kernels push -p kaggle/train/smoke_kernel   (or kaggle/train/l4_kernel)
"""
import argparse
import ast
import base64
import json
import pathlib
import sys
import urllib.request

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "kaggle" / "eval_l4"))
sys.path.insert(0, str(REPO / "kaggle"))
from make_eval_notebook import code, md  # noqa: E402
from owner import mine, src as shared  # noqa: E402

TRAINKIT = REPO / "kaggle" / "train" / "trainkit"
EVALKIT = REPO / "kaggle" / "eval_l4" / "evalkit"
ENV_MODULES = ["__init__", "config", "util", "envsetup"]
TRAIN_MODULES = ["__init__", "config", "data", "model", "prefix", "export", "worker", "launcher", "main"]
CFG_URL = "https://huggingface.co/google/gemma-4-31B-it-qat-q4_0-unquantized/raw/main/config.json"
# Keep serialized source below Kaggle's reported 1 MB notebook-source limit.
# Base64 expands inputs by 4/3; leave room for code and architecture config.
EMBED_MAX_MB = 0.6
SOURCE_MAX_BYTES = 1_000_000


def first_doc_line(path):
    text = path.read_text()
    return text.split('"""')[1].strip().splitlines()[0] if text.startswith('"""') else ""


def build(a):
    data = pathlib.Path(a.data)
    embed = not a.prefix_probe and data.stat().st_size / 1e6 <= EMBED_MAX_MB and not a.dataset
    assert embed or a.dataset or a.prefix_probe, (f"{data} is {data.stat().st_size / 1e6:.2f} MB; embedding it would exceed the "
                                "notebook source budget. Attach it as a dataset and pass --dataset owner/slug.")
    settings = {"name": a.name, "lr": a.lr, "max_windows": a.max_windows, "budget_h": a.budget_h, "smoke": a.smoke,
                "epochs": a.epochs, "grad_accum": a.grad_accum, "save_every": a.save_every, "val_every": a.val_every,
                "prefix_probe": a.prefix_probe}
    cells = [
        md(f"""# LoRA training: `{a.name}` ({'CPU smoke' if a.smoke else '4x L4'})
Generated by `kaggle/train/make_train_notebook.py` from `kaggle/train/trainkit/` (edit there, not here).
Recipe = training probe v4: NF4 from the bf16 QAT weights, LoRA r16 on 410 linears, FSDP over 4 ranks, ≤8k windows,
loss on model-written tokens only. Data: `{data.name}`."""),
        md("## 1. Settings\nEverything the run needs is in `train_cfg.json`; the budget clock starts here."),
        code(f"""import json, os, sys, time
for d in ("/kaggle/working/evalkit", "/kaggle/working/trainkit"):
    os.makedirs(d, exist_ok=True)
TRAIN_CFG = {settings!r}
TRAIN_CFG["t0"] = time.time()
open("/kaggle/working/train_cfg.json", "w").write(json.dumps(TRAIN_CFG, indent=1))
TRAIN_CFG"""),
        md("## 2. Embedded inputs\nTokenized windows (unless attached as a dataset) and, for the smoke model, the real config."),
        code(f"""import base64, pathlib
DATA_B64 = {base64.b64encode(data.read_bytes()).decode() if embed else ''!r}
if DATA_B64:
    pathlib.Path("/kaggle/working/train_data.npz").write_bytes(base64.b64decode(DATA_B64))
G4CFG = {urllib.request.urlopen(CFG_URL, timeout=30).read().decode() if a.smoke else ''!r}
if G4CFG:
    pathlib.Path("/kaggle/working/g4cfg.json").write_text(G4CFG)
print("data embedded:", bool(DATA_B64), "| smoke config:", bool(G4CFG))"""),
        md("## 3. Environment modules (from evalkit)"),
    ]
    for m in ENV_MODULES:
        cells.append(md(f"### `evalkit/{m}.py`\n{first_doc_line(EVALKIT / f'{m}.py')}"))
        cells.append(code(f"%%writefile /kaggle/working/evalkit/{m}.py\n" + (EVALKIT / f"{m}.py").read_text()))
    cells.append(md("## 4. trainkit modules\nOne cell per module."))
    for m in TRAIN_MODULES:
        cells.append(md(f"### `trainkit/{m}.py`\n{first_doc_line(TRAINKIT / f'{m}.py')}"))
        cells.append(code(f"%%writefile /kaggle/working/trainkit/{m}.py\n" + (TRAINKIT / f"{m}.py").read_text()))
    cells += [
        md("## 5. Scorer environment\nRestore the Py3.12 venv, upgrade changed wheels, add peft + bitsandbytes."),
        code(f"""sys.path.insert(0, "/kaggle/working")
from evalkit.envsetup import ScorerEnv
ScorerEnv().prepare_training(gpus={not a.smoke})"""),
        md("## 6. Train\nRuns inside the venv: torchrun over the GPUs (2 CPU ranks for the smoke); streamed here."),
        code("""import subprocess
proc = subprocess.Popen(["/tmp/scorer_host/bin/python", "-m", "trainkit.main"], cwd="/kaggle/working",
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
for line in proc.stdout:
    print(line, end="", flush=True)
print("exit code", proc.wait())"""),
        md("## 7. Results"),
        code("""print(open("/kaggle/working/train_report.json").read()[:20000])"""),
    ]
    for c in cells:  # every code cell must be valid Python before it costs a session
        if c["cell_type"] == "code":
            src = "".join(c["source"])
            ast.parse(src.split("\n", 1)[1] if src.startswith("%%writefile") else src)
    nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                       "language_info": {"name": "python"}}, "nbformat": 4, "nbformat_minor": 4}
    # Match the CLI's source-list normalization before checking the wire size.
    wire_nb = {**nb, "cells": [{**c, "source": "".join(c["source"])} for c in cells]}
    source_bytes = len(json.dumps(wire_nb).encode("utf-8"))
    assert source_bytes < SOURCE_MAX_BYTES, (f"Notebook source is {source_bytes:,} bytes; keep it below "
                                             f"{SOURCE_MAX_BYTES:,}. Move embedded inputs to --dataset.")
    # one notebook per adapter, so a later run never overwrites the output an earlier adapter is served from
    slug = (("gemma4-prefix-probe-smoke" if a.smoke else "gemma4-prefix-probe") if a.prefix_probe else
            "gemma4-train-smoke" if a.smoke else "gemma4-train-lora" if a.name == "conv_lora"
            else "gemma4-train-" + a.name.replace("_", "-"))
    out = REPO / "kaggle" / "train" / (("prefix_probe_smoke" if a.smoke else "l4_prefix_probe") if a.prefix_probe else
                                       "smoke_kernel" if a.smoke else "l4_kernel" if a.name == "conv_lora" else f"l4_{a.name}")
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{slug}.ipynb").write_text(json.dumps(nb, indent=1))
    meta = {"id": mine(slug), "title": slug, "code_file": f"{slug}.ipynb", "language": "python",
            "kernel_type": "notebook", "is_private": True, "enable_gpu": not a.smoke, "enable_internet": False,
            "dataset_sources": ["metric/gemma-4-developer-agent-wheelhouse"] + ([a.dataset] if a.dataset else []),
            "kernel_sources": [shared("gemma4-scorer-env"), shared("gemma4-train-wheels")] +
                              ([shared("gemma4-rftset-rs2")] if a.prefix_probe and not a.smoke else []),  # real tokens
            "model_sources": [] if a.smoke else ["google/gemma-4/Transformers/gemma-4-31b-it-qat-q4_0-unquantized/2"],
            "competition_sources": [] if a.smoke else ["gemma-4-developer-agent"]}
    if not a.smoke:
        meta["machine_shape"] = "NvidiaL4"
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"wrote {out / (slug + '.ipynb')}: {len(cells)} cells, source {source_bytes:,} bytes, "
          f"data {'embedded' if embed else a.dataset}, {settings}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("data")
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--dataset", default=None, help="Kaggle dataset holding the .npz (when too big to embed)")
    ap.add_argument("--name", default="conv_lora")
    ap.add_argument("--lr", type=float, default=1e-4)
    ap.add_argument("--epochs", type=float, default=1.0)
    ap.add_argument("--grad-accum", type=int, default=2)
    ap.add_argument("--max-windows", type=int, default=None)
    ap.add_argument("--budget-h", type=float, default=10.5)
    ap.add_argument("--save-every", type=int, default=0)
    ap.add_argument("--val-every", type=int, default=0)
    ap.add_argument("--prefix-probe", action="store_true", help="PA1: idea A probe (no data; pass 'none' as DATA)")
    build(ap.parse_args())

#!/bin/sh
# Build the A8 Kaggle CPU kernel (Internet ON): a8_body.py with E0b pairs + oblig.py embedded as a base64 tar.gz.
# Shell only; nothing is analysed locally. Then: .venv/bin/kaggle kernels push -p kaggle/a8_bm25/kernel
set -e
cd "$(dirname "$0")/../.."
OUT=kaggle/a8_bm25/kernel
mkdir -p "$OUT"
{
  printf '# Generated by kaggle/a8_bm25/build.sh; edit a8_body.py, not this file.\n'
  printf 'PAYLOAD = "'
  COPYFILE_DISABLE=1 tar czf - results/runs/e0b/e0b_pairs.json tools/oblig.py | base64 | tr -d '\n'
  printf '"\n'
  cat kaggle/a8_bm25/a8_body.py
} > "$OUT/a8_bm25.py"
cat > "$OUT/kernel-metadata.json" <<'EOF'
{
  "id": "shreysharma07/gemma4-a8-bm25",
  "title": "gemma4-a8-bm25",
  "code_file": "a8_bm25.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": false,
  "enable_internet": true,
  "competition_sources": [],
  "dataset_sources": [],
  "model_sources": [],
  "kernel_sources": []
}
EOF
wc -c "$OUT/a8_bm25.py"

#!/bin/sh
# Assemble the RS1 kernel: format_drift.classify + v14's system prompt and declared tools + rft_core -> kernel/build_rftset.py
# Then: .venv/bin/kaggle kernels push -p kaggle/rftset/kernel
set -e
cd "$(dirname "$0")"
REPO=../..
mkdir -p kernel
python3 - "$REPO" > kernel/build_rftset.py <<'PY'
import ast, json, pathlib, re, sys
repo = pathlib.Path(sys.argv[1])
sub = repo / "submissions" / "v14_thinking"
names = re.findall(r"^  - (\w+)\s*$", (sub / "agent.yaml").read_text(), re.M)  # declared order, as served
by = {t.get("function", t)["name"]: t for t in json.loads((repo / "posttrain" / "tool_schemas.json").read_text())}
tools = [by[n] for n in names]
fd = (repo / "analysis" / "format_drift.py").read_text()
fd = fd[fd.index("SCHEMA = {"):fd.index("\ndef main(")]  # SCHEMA, IDENT, classify only
core = (pathlib.Path("rft_core.py")).read_text()
mod = ast.parse(core)
core = "".join(core.splitlines(keepends=True)[mod.body[1].lineno - 1:])  # drop the docstring, keep imports
print('"""RS1 R2 -> thinking-ON training set. Generated by kaggle/rftset/build.sh (edit rft_core.py, not this)."""')
print("import pathlib, re")
print("# ------------------------------------------------------------------ analysis/format_drift.py (classify)")
print(fd)
print(core)
print("# ------------------------------------------------------------------ embedded v14 submission bits")
print(f"SUB = pathlib.Path('/tmp/rftset_sub'); (SUB / 'prompts').mkdir(parents=True, exist_ok=True)")
print(f"(SUB / 'prompts' / 'system.md').write_text({(sub / 'prompts' / 'system.md').read_text()!r})")
print(f"TOOLS = {json.dumps(tools)!r}")
print("main(SUB, json.loads(TOOLS))")
PY
python3 -c "import ast; ast.parse(open('kernel/build_rftset.py').read())"
cat > kernel/kernel-metadata.json <<'JSON'
{
  "id": "shreysharma07/gemma4-rftset",
  "title": "gemma4-rftset",
  "code_file": "build_rftset.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": false,
  "enable_internet": false,
  "competition_sources": [],
  "dataset_sources": ["shreysharma07/gemma4-factory-v0", "shreysharma07/gemma4-factory-v1"],
  "model_sources": ["google/gemma-4/Other/gemma-4-31b-it-qat-w4a16-ct/2"],
  "kernel_sources": ["shreysharma07/gemma4-factory-rollout-s0", "atulbaliyan/gemma4-factory-rollout-s1"]
}
JSON
echo "wrote kernel/build_rftset.py ($(wc -l < kernel/build_rftset.py) lines)"

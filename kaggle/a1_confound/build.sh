#!/bin/sh
# Build the A1 Kaggle CPU kernel: a1_body.py with the run outcomes embedded as a base64 tar.gz PAYLOAD.
# Shell only (tar/base64); nothing is analysed locally. Then: .venv/bin/kaggle kernels push -p kaggle/a1_confound/kernel
set -e
cd "$(dirname "$0")/../.."
R=data/runs
OUT=kaggle/a1_confound/kernel
mkdir -p "$OUT"
{
  printf '# Generated by kaggle/a1_confound/build.sh; edit a1_body.py, not this file.\n'
  printf 'PAYLOAD = "'
  tar czf - -C "$R" \
    eval_v7_new60/x/eval_v7_noedit/rep0/analysis/per_task.jsonl \
    eval_v14_new60_peek/x/eval_v14_thinking/rep0/analysis/per_task.jsonl \
    rs_v7_valid/x/eval_v7_noedit/rep0/analysis/per_task.jsonl \
    rs_v7_valid/x/eval_v7_noedit/rep1/analysis/per_task.jsonl \
    rs_v7_valid/x/eval_v7_noedit/rep2/analysis/per_task.jsonl \
    rs_v7_valid/x/eval_v7_noedit/rep3/analysis/per_task.jsonl \
    rs_v7_valid/x/eval_v7_noedit/rep4/analysis/per_task.jsonl \
    xg/results.jsonl xg/tasks_meta.jsonl | base64 | tr -d '\n'
  printf '"\n'
  cat kaggle/a1_confound/a1_body.py
} > "$OUT/a1_confound.py"
cat > "$OUT/kernel-metadata.json" <<'EOF'
{
  "id": "shreysharma07/gemma4-a1-confound",
  "title": "gemma4-a1-confound",
  "code_file": "a1_confound.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": false,
  "enable_internet": false,
  "competition_sources": ["gemma-4-developer-agent"],
  "dataset_sources": [],
  "model_sources": [],
  "kernel_sources": []
}
EOF
wc -c "$OUT/a1_confound.py"

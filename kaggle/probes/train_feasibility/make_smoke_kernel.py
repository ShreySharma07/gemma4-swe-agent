"""
Write a Kaggle CPU kernel that smoke-tests probe_train.py (PROBE_SMOKE=1: tiny random Gemma-4, FSDP on gloo, 2 ranks)
inside the same offline scorer env + train wheels the L4 run uses. Free CPU quota; nothing runs on the local machine.
Push with: .venv/bin/kaggle kernels push -p kaggle/probes/train_feasibility/smoke_cpu
"""
import base64
import json
import pathlib
import urllib.request

HERE = pathlib.Path(__file__).parent
OUT = HERE / "smoke_cpu"
OUT.mkdir(exist_ok=True)
CFG_URL = "https://huggingface.co/google/gemma-4-31B-it-qat-q4_0-unquantized/raw/main/config.json"

src = base64.b64encode((HERE / "probe_train.py").read_bytes()).decode()
cfg = urllib.request.urlopen(CFG_URL, timeout=30).read().decode()
script = f'''# Generated by kaggle/probes/train_feasibility/make_smoke_kernel.py from probe_train.py (do not edit here).
import base64, os, pathlib, subprocess, sys
W = pathlib.Path("/kaggle/working")
(W / "probe_train.py").write_bytes(base64.b64decode({src!r}))
(W / "g4cfg.json").write_text({cfg!r})
env = dict(os.environ, PROBE_SMOKE="1", PROBE_OUT=str(W / "smoke"), PROBE_SMOKE_CONFIG=str(W / "g4cfg.json"))
proc = subprocess.Popen([sys.executable, str(W / "probe_train.py")], env=env, stdout=subprocess.PIPE,
                        stderr=subprocess.STDOUT, text=True)
for line in proc.stdout:
    print(line, end="", flush=True)
print("exit code", proc.wait())
'''
(OUT / "smoke_cpu.py").write_text(script)
(OUT / "kernel-metadata.json").write_text(json.dumps({
    "id": "shreysharma07/gemma4-train-probe-smoke", "title": "gemma4-train-probe-smoke", "code_file": "smoke_cpu.py",
    "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_internet": False,
    "competition_sources": [], "dataset_sources": [], "model_sources": [],
    "kernel_sources": ["shreysharma07/gemma4-scorer-env", "shreysharma07/gemma4-train-wheels"]}, indent=2) + "\n")
print("wrote", OUT)

#!/bin/sh
# Build the A8b Kaggle CPU kernel (E0a under oblig.py v2, post hoc). Shell only. Then: kaggle kernels push -p kaggle/a8b_e0a_v2/kernel
set -e
cd "$(dirname "$0")/../.."
OUT=kaggle/a8b_e0a_v2/kernel
mkdir -p "$OUT"
{
  printf '# Generated by kaggle/a8b_e0a_v2/build.sh; edit a8b_body.py, not this file.\n'
  printf 'PAYLOAD = "'
  COPYFILE_DISABLE=1 tar czf - tools/oblig.py analysis/e0a_obligation_recall.py analysis/exec_graph_analysis.py \
    analysis/obligation_pilot.py | base64 | tr -d '\n'
  printf '"\n'
  cat kaggle/a8b_e0a_v2/a8b_body.py
} > "$OUT/a8b_e0a_v2.py"
cat > "$OUT/kernel-metadata.json" <<'JSON'
{
  "id": "shreysharma07/gemma4-a8b-e0a-v2",
  "title": "gemma4-a8b-e0a-v2",
  "code_file": "a8b_e0a_v2.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": false,
  "enable_internet": false,
  "competition_sources": [],
  "dataset_sources": [],
  "model_sources": [],
  "kernel_sources": ["shreysharma07/gemma4-exec-graphs"]
}
JSON
wc -c "$OUT/a8b_e0a_v2.py"
